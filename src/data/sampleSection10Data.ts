function rect(x: number, y: number, w: number, h: number): Point2D[] {
  return [
    { x: OX + x, y: OY + y },
    { x: OX + x + w, y: OY + y },
    { x: OX + x + w, y: OY + y + h },
    { x: OX + x, y: OY + y + h },
  ];
}

