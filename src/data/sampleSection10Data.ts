const DOL_DX = -12.4;
const DOL_DY = 18.6;

function makeDolParcel(
  id: string,
  ltaxParcelCode: string,
  deedNo: string,
  landNo: string,
  surveyNo: string,
  ownerName: string,
  ownerId: string,
  ownerAddress: string,
  baseRect: Point2D[],
  landUse: DolSection10Parcel['landUse'],
  assessedPricePerSqWa: number,
  status: DolSection10Parcel['status'],
  note: string,
  building: DolSection10Parcel['building'],
  jitter = 0.5,
  overrideDolSqWa?: number
): DolSection10Parcel {
  const rawPolygon = baseRect.map((p, idx) => ({
    x: Math.round((p.x + DOL_DX + (idx % 2 === 0 ? jitter : -jitter)) * 100) / 100,
    y: Math.round((p.y + DOL_DY + (idx > 1 ? jitter : -jitter)) * 100) / 100,
  }));
  const areaSqM = polygonAreaSqMeters(baseRect);
  const { rai, ngan, sqWa, totalSqWa } = sqMetersToRaiNganWa(areaSqM);
  const dolSqWa = overrideDolSqWa ?? totalSqWa;
  const dolUnits = sqMetersToRaiNganWa(dolSqWa * 4);

  return {
    id,
    ltaxParcelCode,
    zone: 'PS',
    block: '1',
    lot: ltaxParcelCode.replace('PS', ''),
    deedType: 'โฉนดที่ดิน',
    deedNo,
    utmMap: '5842 IV 4820-02',
    landNo,
    surveyNo,
    tambon: 'พระซอง',
    amphoe: 'นาแก',
    province: 'นครพนม',
    ownerName,
    ownerId,
    ownerAddress,
    rai: dolUnits.rai,
    ngan: dolUnits.ngan,
    sqWa: dolUnits.sqWa,
    dolSqWa,
    landUse,
    assessedPricePerSqWa,
    building,
    rawPolygon,
    adjustedPolygon: rawPolygon.map((p) => ({ ...p })),
    status,
    shiftDistanceM: Math.round(Math.hypot(DOL_DX, DOL_DY) * 100) / 100,
    snappedVerticesCount: 0,
    calculatedSqWa: totalSqWa,
    areaDiffPercent:
      Math.round((Math.abs(totalSqWa - dolSqWa) / Math.max(1, dolSqWa)) * 1000) / 10,
    note,
    selectedForPt7: true,
  };
}

