// Incoming Section 10 parcels from Department of Lands (with realistic Indian 1975 datum shift + micro-slivers + split parcels)
function shiftPts(pts: Point2D[], dx: number, dy: number, jitterX = 0, jitterY = 0): Point2D[] {
  return pts.map((p, idx) => ({
    x: Math.round((p.x + dx + (idx % 2 === 0 ? jitterX : -jitterX * 0.4)) * 100) / 100,
    y: Math.round((p.y + dy + (idx > 1 ? jitterY : -jitterY * 0.4)) * 100) / 100,
  }));
}

// Simulated DOL offset (~ -16.5m East, +22.8m North) typical of uncalibrated DOL-LTAX layer mismatch
const DOL_DX = -16.5;
const DOL_DY = 22.8;

function makeDolParcel(
  id: string,
  ltaxParcelCode: string,
  deedNo: string,
  landNo: string,
  surveyNo: string,
  ownerName: string,
  ownerId: string,
  ownerAddress: string,
  baseRect: Point2D[],
  landUse: DolSection10Parcel['landUse'],
  assessedPricePerSqWa: number,
  status: DolSection10Parcel['status'],
  note: string,
  building: DolSection10Parcel['building'],
  jitter = 0.6,
  overrideDolSqWa?: number
): DolSection10Parcel {
  const rawPolygon = shiftPts(baseRect, DOL_DX, DOL_DY, jitter, jitter * 0.8);
  const areaSqM = polygonAreaSqMeters(baseRect);
  const { rai, ngan, sqWa, totalSqWa } = sqMetersToRaiNganWa(areaSqM);
  const dolSqWa = overrideDolSqWa ?? totalSqWa;
  const dolUnits = sqMetersToRaiNganWa(dolSqWa * 4);

  return {
    id,
    ltaxParcelCode,
    zone: ltaxParcelCode.slice(0, 2),
    block: ltaxParcelCode.slice(2, 3),
    lot: ltaxParcelCode.slice(3),
    deedType: 'โฉนดที่ดิน',
    deedNo,
    utmMap: '5137 III 6854-04',
    landNo,
    surveyNo,
    tambon: 'คลองหนึ่ง',
    amphoe: 'คลองหลวง',
    province: 'ปทุมธานี',
    ownerName,
    ownerId,
    ownerAddress,
    rai: dolUnits.rai,
    ngan: dolUnits.ngan,
    sqWa: dolUnits.sqWa,
    dolSqWa,
    landUse,
    assessedPricePerSqWa,
    building,
    rawPolygon,
    adjustedPolygon: rawPolygon.map((p) => ({ ...p })),
    status,
    shiftDistanceM: Math.round(Math.hypot(DOL_DX, DOL_DY) * 100) / 100,
    snappedVerticesCount: 0,
    calculatedSqWa: totalSqWa,
    areaDiffPercent:
      Math.round((Math.abs(totalSqWa - dolSqWa) / Math.max(1, dolSqWa)) * 1000) / 10,
    note,
    selectedForPt7: true,
  };
}

